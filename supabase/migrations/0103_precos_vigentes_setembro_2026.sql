      join public.price_tables pt on pt.id = i.price_table_id
     where pt.codigo = t.codigo and pt.vigente_ate is null;
    if n <> 319 then
      raise exception 'ABORTADO: % ficou com % itens, e o PDF tem 319', t.nome, n;
    end if;
  end loop;

  select count(*) into n from public.price_tables where vigente_ate is null;
  if n <> 4 then raise exception 'ABORTADO: % tabelas vigentes, e sao 4', n; end if;

  select count(*) into n from public.price_table_items where preco <= 0;
  if n > 0 then raise exception 'ABORTADO: % item(ns) com preco zerado', n; end if;

  select count(*) into n
    from public.price_table_items i
    join public.price_tables pt on pt.id = i.price_table_id and pt.vigente_ate is null
    join public.products p on p.code = i.codigo
   where p.carton_quantity is distinct from i.qtd_caixa;
  if n > 0 then
    raise exception 'ABORTADO: % item(ns) com quantidade por caixa diferente do cadastro', n;
  end if;
